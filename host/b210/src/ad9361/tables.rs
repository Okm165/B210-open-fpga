/// The FIR coefficients for `taps` taps and a FIR rate change of `factor`
/// (2: half-band, 4: low-pass at fs/4), for the combinations the rate
/// setup reaches (`Ad9361::setup_rates`: 128 taps at either factor, 96 and
/// 64 taps only at 2). UHD also carries 48-tap sets and x4 sets of 64 and 96
/// taps; no rate selects them, so they are left out.
pub fn fir(taps: usize, factor: u32) -> Option<&'static [i16]> {
    match (taps, factor) {
        (128, 4) => Some(&FIR128_X4),
        (128, 2) => Some(&HB127),
        (96, 2) => Some(&HB95),
        (64, 2) => Some(&HB63),
        _ => None,
    }
}

