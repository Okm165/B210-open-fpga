#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn filters_are_symmetric_with_unit_centre() {
        // linear phase: h[k] = h[n - 1 - k] over the designed taps (the 127-tap
        // half-band is padded with one zero to 128)
        for (h, n) in [(&HB127[..], 127), (&HB95[..], 95), (&HB63[..], 63)] {
            assert!((0..n).all(|k| h[k] == h[n - 1 - k]), "{n}");
            assert_eq!(h[n / 2], 32767);
        }
        let h = &FIR128_X4;
        assert!((0..128).all(|k| h[k] == h[127 - k]));
        // fir1 normalises the DC gain to 1: the rounded taps sum to ~2^16
        let dc: i32 = h.iter().map(|&c| c as i32).sum();
        assert!((dc - 65536).abs() < 64, "{dc}");
    }

    #[test]
    fn vco_bands_descend() {
        assert!(VCO_BAND.windows(2).all(|w| w[0] > w[1]));
    }
}
